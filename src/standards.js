export function getStandard(code) {
  return HA6_STANDARDS.find((item) => item.code === code);
}

export function standardsByPart() {
  return HA6_STANDARDS.reduce((groups, standard) => {
    const part = standard.code.split("-")[0];
    groups[part] ??= [];
    groups[part].push(standard);
    return groups;
  }, {});
}
